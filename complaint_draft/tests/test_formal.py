@pytest.mark.parametrize("src,want", DA)
def test_plain_to_formal(src, want):
    assert formalize(src, plain=True) == want


def test_plain_endings_are_left_alone_unless_asked():
    assert formalize("버스가 줄었다") == "버스가 줄었다"


@pytest.mark.parametrize("src", ["버스가 정말 안 오네요", "원래 있었거든요", "언제 고쳐 주나요?", "버스 증차", "버스가 줄었습니다.",
                                 "우리 동네 버스가 확 줄어부난 할망덜 병원 가기가 막 힘들어마씸", "길을 걸어요", "[교통] 구좌읍"])
def test_uncertain_or_non_sentences_are_unchanged(src):
    assert formalize(src, plain=False) == src


def test_only_sentence_ends_change_and_lines_are_kept():
    src = "버스가 줄어서 힘들어요. 병원도 멀어요.\n- 의자가 없어요"
    assert formalize(src) == "버스가 줄어서 힘듭니다. 병원도 멉니다.\n- 의자가 없습니다"


def test_has_informal_flags_leftovers():
    assert has_informal("버스가 정말 안 오네요") and has_informal("괜찮아요.\n다음") and not has_informal("버스 증차")
